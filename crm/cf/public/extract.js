// Boundary-aware regex without lookbehind (old Safari): group 1 is the char before the match, the match proper starts at m.index + m[1].length.
function bound(src, flags) { return new RegExp('(^|[^\\p{L}\\p{N}])(?:' + src + ')(?![\\p{L}\\p{N}])', flags || 'iu'); }
function boundAll(src) { return bound(src, 'giu'); }
function cap(w) { return w ? w.charAt(0).toUpperCase() + w.slice(1) : w; }
function titleCase(s) { return s.toLowerCase().replace(/(^|[\s-])(\p{L})/gu, function (m, a, b) { return a + b.toUpperCase(); }); }
function clean(s) { return String(s == null ? '' : s).replace(/[ ​-‏⁠﻿]/g, ' ').replace(/\r/g, '').trim(); }
function stripPhones(s) { return s.replace(/\+?\d[\d\s\-()]{6,}\d/g, ' '); }

