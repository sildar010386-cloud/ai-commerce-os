var STREET_BEFORE = /^(?:ул|улица|пр|пр-т|пр-кт|проспект|мкр|микрорайон|пер|переулок|бульвар|б-р|им|имени|жк)$/i;

function normCity(s) { return String(s).toLowerCase().replace(/ё/g, 'е'); }
function dictCity(text) {
  var low = normCity(text), best = null;
  CITIES.forEach(function (c) {
    c.re.lastIndex = 0;
    var m;
    while ((m = c.re.exec(low))) {
      var at = m.index + m[1].length;
      if (c.ambiguous && !/\p{Lu}/u.test(text.charAt(at))) { c.re.lastIndex = at + 1; continue; }
      var pm = low.slice(0, at).match(/([\p{L}-]+)\.?\s*$/u);
      if (pm && STREET_BEFORE.test(pm[1])) { c.re.lastIndex = at + 1; continue; }
      if (!best || at < best.at) best = { name: c.name, at: at, len: m[0].length - m[1].length };
      break;
    }
  });
  return best;
}
var CITY_MARK = /(^|[^\p{L}\p{N}])(?:г|гор|город)\.?\s*(?=\S)/giu;
function findCity(text) {
  // 1. explicit «г. X» / «город X»
  var m;
  CITY_MARK.lastIndex = 0;
  while ((m = CITY_MARK.exec(text))) {
    var from = m.index + m[0].length, rest = text.slice(from, from + 40);
    var d = dictCity(rest);
    if (d && d.at === 0) return d.name;
    var w = rest.match(/^(\p{Lu}[\p{L}-]{2,})/u);
    if (w) return w[1];
  }
  // 2. «X қ.» / «X қаласы»
  m = text.match(/(^|[^\p{L}\p{N}])(\p{Lu}[\p{L}-]{2,})\s+(?:қ\.|қаласы|қала)(?![\p{L}\p{N}])/u);
  if (m) { var d2 = dictCity(m[2]); return d2 ? d2.name : m[2]; }
  // 3. known city
  var d3 = dictCity(text);
  if (d3) return d3.name;
  // 4. village / settlement
  m = text.match(/(^|[^\p{L}\p{N}])(?:с\.|село|пос\.|поселок|посёлок|аул|ауыл)\s*(\p{Lu}[\p{L}-]{2,})/u);
  return m ? m[2] : '';
}
function stripCities(s) {
  var low = normCity(s), out = s;
  CITIES.forEach(function (c) {
    c.re.lastIndex = 0;
    var m, cuts = [];
    while ((m = c.re.exec(low))) { cuts.push([m.index + m[1].length, m.index + m[0].length]); }
    cuts.reverse().forEach(function (k) { out = out.slice(0, k[0]) + ' ' + out.slice(k[1]); low = low.slice(0, k[0]) + ' ' + low.slice(k[1]); });
  });
  return out;
}

