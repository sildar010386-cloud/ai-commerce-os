var STRONG = bound('ул|улица|проспект|пр-т|пр-кт|просп|пр|мкр|мкр-н|микрорайон|пер|переулок|бульвар|б-р|көшесі|көше|шағын\\s*аудан\\w*|жк|трасса|шоссе|квартал|кв-л', 'iu');
var STRONG_G = boundAll('ул|улица|проспект|пр-т|пр-кт|просп|пр|мкр|мкр-н|микрорайон|пер|переулок|бульвар|б-р|көшесі|көше|шағын\\s*аудан\\w*|жк|трасса|шоссе|квартал|кв-л');
var WEAK = bound('(?:д|дом|кв|квартира|офис|оф|корпус|корп|подъезд|этаж)\\.?\\s*[№#]?\\s*\\d+', 'iu');
var REGION = /(^|[^\p{L}\p{N}])(\p{L}[\p{L}-]+)\s+(?:обл\.?|область|облысы|р-н|район|ауданы)(?![\p{L}\p{N}])/iu;
var VILLAGE = /(^|[^\p{L}\p{N}])(?:с\.|село|пос\.|поселок|посёлок|аул|ауыл)\s*\p{Lu}/iu;
function markerIndex(s) {
  var idx = -1;
  [STRONG, WEAK, REGION, VILLAGE].forEach(function (re) {
    var m = re.exec(s);
    if (m) { var at = m.index + m[1].length; if (idx < 0 || at < idx) idx = at; }
  });
  return idx;
}
function hasStrong(s) { return STRONG.test(s); }
// Splits a message into trimmed lines, each into comma pieces; sentences are split on «!», «?» and on a period after a long word.
function pieces(text) {
  var lines = text.replace(/(\p{L}{5,})\.\s+/gu, '$1\n').replace(/[!?]+\s*/g, '\n').split('\n');
  var out = [];
  lines.forEach(function (ln) {
    ln = ln.replace(/^\s*(?:\d{1,2}[.)]|[-•*–—])\s+/, '').trim();
    if (!ln) return;
    var ps = ln.split(/\s*[,;]\s*/).map(function (p) { return p.trim(); }).filter(Boolean);
    out.push(ps);
  });
  return out;
}

