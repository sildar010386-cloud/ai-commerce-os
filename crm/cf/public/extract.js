var SURNAME = /(?:ов|ова|ев|ева|ёв|ёва|ин|ина|ын|ына|ский|ская|цкий|цкая|ұлы|улы|қызы|кызы|оглы|ович|евич|ьич|овна|евна|ична|инична)$/;
var CYR_CAP = /^\p{Lu}\p{Ll}+(?:-\p{Lu}\p{Ll}+)?$/u;
var CYR = /^[\p{Script=Cyrillic}-]+$/u;
function isStop(w) { return !!STOP[w.toLowerCase()]; }
function tidyTokens(piece) {
  return piece.split(/\s+/).map(function (t) { return t.replace(/^[^\p{L}]+|[^\p{L}]+$/gu, ''); }).filter(Boolean);
}
// Capitalised Cyrillic words that look like a person's name, '' otherwise.
function nameFromPiece(piece) {
  piece = stripCities(stripPhones(piece)).replace(/(^|[^\p{L}])(?:г|гор|город)\.?(?![\p{L}])/giu, ' ');
  if (/[\d@]/.test(piece)) return '';
  var tk = tidyTokens(piece);
  while (tk.length && isStop(tk[0])) tk.shift();
  while (tk.length && isStop(tk[tk.length - 1])) tk.pop();
  if (tk.length && tk.every(function (t) { return t === t.toUpperCase(); }) && tk.length >= 2) tk = tk.map(titleCase);
  if (tk.length < 2 || tk.length > 3) return '';
  if (!tk.every(function (t) { return CYR.test(t) && CYR_CAP.test(t) && !isStop(t) && !NOT_NAME[t.toLowerCase()]; })) return '';
  if (!tk.some(function (t) { return SURNAME.test(t.toLowerCase()); })) return '';
  return tk.join(' ');
}
var NAME_MARK = boundAll('фио(?:\\s+получателя)?|фамилия,?\\s+имя(?:,?\\s+отчество)?|имя|получатель|меня\\s+зовут|зовут\\s+меня|мо[её]\\s+имя|на\\s+имя');
function nameFromMarker(text) {
  var m;
  NAME_MARK.lastIndex = 0;
  while ((m = NAME_MARK.exec(text))) {
    var rest = text.slice(m.index + m[0].length).replace(/^[\s:=\-–—]+/, '');
    rest = stripPhones(rest.split(/[\n,;()!?]|\.(?:\s|$)/)[0]);
    var tk = tidyTokens(rest), out = [];
    for (var i = 0; i < tk.length && out.length < 3; i++) {
      var t = tk[i];
      if (!CYR.test(t) || isStop(t) || NOT_NAME[t.toLowerCase()]) break;
      var allCaps = t.length > 1 && t === t.toUpperCase();
      if (allCaps) t = titleCase(t);
      if (i === 0) t = cap(t);
      else if (!CYR_CAP.test(t) && !SURNAME.test(t.toLowerCase())) break;
      else t = cap(t);
      out.push(t);
    }
    if (out.length) return out.join(' ');
  }
  return '';
}

/* ---------- index ---------- */
var IDX = /(^|[^\d])((?:0[1-9]|1[0-6])\d{4})(?!\d)/g;
var CURRENCY = /^\s*(?:тг|тенге|₸|kzt|руб|р\b|т\b|тыс|сом|usd|\$|доллар|%|шт)/i;
var PRICE_HEAD = /(?:цена|сумм|стоим|итого|оплат|перевел|перевёл|скинул|предоплат|₸|тг|тенге|чек|тел|номер|whatsapp|ватсап|вацап|моб|иин|бин)[^\d]{0,12}$/i;
function findIndex(text) {
  var addrMsg = markerIndex(text) >= 0, m;
  IDX.lastIndex = 0;
  while ((m = IDX.exec(text))) {
    var start = m.index + m[1].length, end = start + 6;
    var head = text.slice(Math.max(0, start - 24), start), tail = text.slice(end, end + 12);
    var prev = text.charAt(start - 1), prev2 = text.charAt(start - 2), next = text.charAt(end);
    if (prev === '+' || prev === '-' || ((prev === '.' || prev === ',') && /\d/.test(prev2)) || ((next === '.' || next === ',') && /\d/.test(text.charAt(end + 1)))) continue;
    if (/(?:индекс|инд\.?|почтов\p{L}*|zip|postal|index)[^\d]{0,12}$/iu.test(head)) return m[2];
    if (CURRENCY.test(tail) || PRICE_HEAD.test(head)) continue;
    if (addrMsg) return m[2];
  }
  return '';
}

/* ---------- address line ---------- */
function addressOf(text, known) {
  var parts = [], prevAddr = false;
  pieces(text).forEach(function (line) {
    line.forEach(function (p) {
      p = stripPhones(p).replace(/\s+/g, ' ').trim();
      var at = markerIndex(p);
      if (at >= 0) {
        if (at > 0) {
          var lead = p.slice(0, at), rest = stripCities(lead).replace(/(^|[^\p{L}])(?:г|гор|город)\.?(?![\p{L}])/giu, ' ');
          rest = rest.replace(/[\s,.:;-]+/g, ' ').trim();
          if (known.fullName) known.fullName.split(' ').forEach(function (w) { rest = rest.split(w).join(' ').trim(); });
          var tk = tidyTokens(rest).filter(function (t) { return !isStop(t); });
          if (!tk.length || (nameFromPiece(lead) && !hasStrong(lead))) p = p.slice(at);
        }
        parts.push(p); prevAddr = true;
      } else if (prevAddr && /^\d{1,4}[\p{L}]?(?:\/\d{1,3})?$/u.test(p)) {
        parts.push(p);
      } else prevAddr = false;
    });
  });
  var s = parts.join(', ');
  if (s.length > MAX_ADDRESS) { var cut = s.lastIndexOf(', ', MAX_ADDRESS); s = s.slice(0, cut > 40 ? cut : MAX_ADDRESS); }
  return s.trim();
}

// messages: array of incoming text strings, NEWEST FIRST (the order of ORDER BY ts DESC). Only the first 30 are scanned.
// Each field comes from the newest message that has it (names: an explicit marker anywhere beats a bare name line).
// Returns {fullName, city, address, index}; every field is '' when nothing reliable was found. Never guesses.
function extractOrderFields(messages) {
  var msgs = (Array.isArray(messages) ? messages : []).slice(0, MAX_MESSAGES).map(clean).filter(Boolean);
  var res = { fullName: '', city: '', address: '', index: '' };
  var i;
  for (i = 0; i < msgs.length && !res.fullName; i++) res.fullName = nameFromMarker(msgs[i]);
  for (i = 0; i < msgs.length && !res.fullName; i++) {
    pieces(msgs[i]).some(function (line) {
      return line.some(function (p) {
        var at = markerIndex(p);
        res.fullName = nameFromPiece(at > 0 ? p.slice(0, at) : at === 0 ? '' : p);
        return !!res.fullName;
      });
    });
  }
  for (i = 0; i < msgs.length && !res.city; i++) res.city = findCity(msgs[i]);
  for (i = 0; i < msgs.length && !res.address; i++) res.address = addressOf(msgs[i], res);
  for (i = 0; i < msgs.length && !res.index; i++) res.index = findIndex(msgs[i]);
  return res;
}
